// Build the extension's finite icon inventory from its installed vector libraries.
// No remote catalog is used. See THIRD_PARTY_NOTICES.md for attribution.
import fs from "node:fs"
import path from "node:path"
import * as remix from "@remixicon/react"
import * as tabler from "@tabler/icons-react"
import * as lucide from "lucide-react"
import { createElement } from "react"
import { renderToStaticMarkup } from "react-dom/server"

function files(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name)
    return e.isDirectory()
      ? /^(?:__tests__|migration-scripts|locales)$/.test(e.name)
        ? []
        : files(p)
      : /\.[jt]sx?$/.test(p)
        ? [p]
        : []
  })
}
const ids = new Set(["tabler:question-mark", "tabler:language", "tabler:bulb", "tabler:cards"])
for (const f of files("src"))
  for (const m of fs
    .readFileSync(f, "utf8")
    .matchAll(/["'`]((?:tabler|ri|lucide):[a-z0-9-]+)["'`]/g))
    ids.add(m[1])
const pascal = (s) =>
  s
    .split("-")
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join("")
const data = {}
const missing = []
const tablerIcons = new Map(Object.entries(tabler))
const remixIcons = new Map(Object.entries(remix))
const lucideIcons = new Map(Object.entries(lucide))
for (const id of [...ids].sort()) {
  const [prefix, name] = id.split(":")
  const component =
    prefix === "tabler"
      ? tablerIcons.get(`Icon${pascal(name)}`)
      : prefix === "ri"
        ? remixIcons.get(`Ri${pascal(name)}`)
        : lucideIcons.get(pascal(name))
  if (!component) {
    missing.push(id)
    continue
  }
  const svg = renderToStaticMarkup(createElement(component))
  const attrs = svg.match(/^<svg([^>]*)>/)?.[1] ?? ""
  const body = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "")
  const outer = attrs.replace(/\s(?:class|width|height|viewBox|xmlns)="[^"]*"/g, "")
  data[id] = { body: `<g${outer}>${body}</g>`, width: 24, height: 24 }
}
if (missing.length) throw new Error(`Missing local icons: ${missing.join(", ")}`)
fs.writeFileSync(
  "src/utils/iconify/bundled-icons-data.ts",
  `// Generated by scripts/generate-bundled-icons.mjs. Local vectors; see THIRD_PARTY_NOTICES.md.\nexport const BUNDLED_ICONS = ${JSON.stringify(data, null, 2)} as const\n`,
)
console.log(`Bundled ${Object.keys(data).length} local icons`)
