function expected(value: any): any {
  if (typeof value === "string") return expectedTags[value] ?? value
  if (Array.isArray(value)) return value.map(expected)
  if (value && typeof value === "object")
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [expectedTags[key] ?? key, expected(item)]),
    )
  return value
}
